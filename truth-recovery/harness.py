"""Truth-recovery harness for MetaFrontierLab.

Measures COVERAGE of the true pooled mean (mu) under a known random-effects
DGP with optional publication selection. Compares the repo's OWN estimator
(FrontierMetaAnalyzer / TBEMA) against a standard DerSimonian-Laird + Wald
reference baseline implemented locally for reference only.

Datasets are generated by gen_datasets.mjs (single-sourced DGP) and piped in
as JSON so the JS DGP kit is the single source of truth.

ADDITIVE: imports the repo verbatim, adds no changes to metafrontier/*.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys

import numpy as np
import pandas as pd
from scipy.stats import norm

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, REPO)

from metafrontier import FrontierMetaAnalyzer, make_tbema_analyzer  # noqa: E402


def gen_datasets(scenario: str, n_reps: int, k: int, mu: float, tau2: float,
                 seed0: int = 1000) -> dict:
    """Invoke the JS DGP generator and parse its JSON output."""
    script = os.path.join(HERE, "gen_datasets.mjs")
    out = subprocess.run(
        ["node", script, scenario, str(n_reps), str(k), str(mu), str(tau2), str(seed0)],
        capture_output=True, text=True, cwd=HERE, check=True,
    )
    return json.loads(out.stdout)


def dl_wald(y: np.ndarray, se: np.ndarray) -> tuple[float, float, float]:
    """DerSimonian-Laird random-effects pool with Wald CI. Reference baseline."""
    v = se ** 2
    w = 1.0 / v
    mu_fe = np.sum(w * y) / np.sum(w)
    q = float(np.sum(w * (y - mu_fe) ** 2))
    k = len(y)
    c = float(np.sum(w) - np.sum(w ** 2) / np.sum(w))
    tau2 = max((q - (k - 1)) / c, 0.0) if c > 0 else 0.0
    w_re = 1.0 / (v + tau2)
    mu_re = float(np.sum(w_re * y) / np.sum(w_re))
    se_re = float(np.sqrt(1.0 / np.sum(w_re)))
    z = norm.ppf(0.975)
    return mu_re, mu_re - z * se_re, mu_re + z * se_re


def run_scenario(scenario: str, n_reps: int = 400, k: int = 15,
                 mu: float = 0.4, tau2: float = 0.04) -> dict:
    payload = gen_datasets(scenario, n_reps, k, mu, tau2)
    datasets = payload["datasets"]

    analyzer = make_tbema_analyzer()

    fm_cov = fm_bias = fm_width = fm_ok = 0
    dl_cov = dl_bias = dl_width = 0
    naive_bias = 0.0

    for ds in datasets:
        y = np.asarray(ds["y"], dtype=float)
        se = np.asarray(ds["se"], dtype=float)
        naive_bias += float(np.mean(y)) - mu

        # Reference DL + Wald
        m_dl, lo_dl, hi_dl = dl_wald(y, se)
        dl_bias += m_dl - mu
        dl_width += hi_dl - lo_dl
        if lo_dl <= mu <= hi_dl:
            dl_cov += 1

        # Repo's own estimator (TBEMA model-averaged stack)
        try:
            df = pd.DataFrame({"effect": y, "se": se})
            res = analyzer.fit(df, effect_col="effect", se_col="se")
            fm_ok += 1
            fm_bias += res.estimate - mu
            fm_width += res.ci_high - res.ci_low
            if res.ci_low <= mu <= res.ci_high:
                fm_cov += 1
        except Exception:
            pass

    n = len(datasets)
    nfm = max(fm_ok, 1)
    return {
        "scenario": scenario, "n_reps": n, "k": k, "mu": mu, "tau2": tau2,
        "naive_bias": naive_bias / n,
        "dl_coverage": dl_cov / n, "dl_bias": dl_bias / n, "dl_width": dl_width / n,
        "fm_coverage": fm_cov / nfm, "fm_bias": fm_bias / nfm,
        "fm_width": fm_width / nfm, "fm_converged": fm_ok,
    }


def main() -> None:
    scenarios = sys.argv[1].split(",") if len(sys.argv) > 1 else \
        ["none", "step_strong", "copas_strong"]
    n_reps = int(sys.argv[2]) if len(sys.argv) > 2 else 300
    print(f"{'scenario':<14} {'naiveBias':>9} | {'DL cov':>7} {'DL bias':>8} {'DL wid':>7} "
          f"| {'FM cov':>7} {'FM bias':>8} {'FM wid':>7} {'FMconv':>7}")
    results = []
    for sc in scenarios:
        r = run_scenario(sc, n_reps=n_reps)
        results.append(r)
        print(f"{r['scenario']:<14} {r['naive_bias']:>9.3f} | "
              f"{r['dl_coverage']:>7.3f} {r['dl_bias']:>8.3f} {r['dl_width']:>7.3f} | "
              f"{r['fm_coverage']:>7.3f} {r['fm_bias']:>8.3f} {r['fm_width']:>7.3f} "
              f"{r['fm_converged']:>7d}")
    out = os.path.join(HERE, "results.json")
    with open(out, "w") as f:
        json.dump(results, f, indent=2)
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
